#include <iostream>
using namespace std;

int main()
{
    int number = 25;
    float price = 199.99f;
    double pi = 3.14159265;
    char letter = 'C';
    bool passed = true;

    cout << "Integer: " << number << endl;
    cout << "Float: " << price << endl;
    cout << "Double: " << pi << endl;
    cout << "Character: " << letter << endl;
    cout << "Boolean: " << passed << endl;

    return 0;
}
